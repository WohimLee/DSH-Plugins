import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { ROOT, categories, validatedPlugins } from './plugin-lib.mjs';
export function renderCatalog(plugins) {
  let text = '# 插件目录\n\n<!-- Generated by pnpm catalog:generate; do not edit. -->\n\n';
  text += `当前 ${plugins.length} 个插件；脚手架不计入目录。状态来自插件声明，verified 需附证据。\n\n`;
  for (const c of categories) {
    text += `## ${c.title}（${c.id}）\n\n`;
    const rows = plugins.filter(p => p.category === c.id);
    if (!rows.length) { text += '尚无插件。\n\n'; continue; }
    text += '| 插件 | 版本 | 用途 | DSH | Web / Desktop / Headless |\n| --- | --- | --- | --- | --- |\n';
    for (const p of rows) {
      const states = ['web', 'desktop', 'headless'].map(s => p.meta.surfaces[s].status).join(' / ');
      text += `| [${p.manifest.name}](../plugins/${p.category}/${p.slug}/README.md) | ${p.manifest.version} | ${p.manifest.description} | ${p.manifest.engines.dsh.replaceAll('|', '&#124;')} | ${states} |\n`;
    }
    text += '\n';
  }
  return `${text.trimEnd()}\n`;
}
if (process.argv[1] && resolve(process.argv[1]) === resolve(ROOT, 'scripts/generate-catalog.mjs')) {
  try {
    const args = process.argv.slice(2);
    if (args.length && (args.length !== 1 || args[0] !== '--check')) throw new Error('Usage: generate-catalog.mjs [--check]');
    const output = resolve(ROOT, 'docs/plugins.md'), expected = renderCatalog(await validatedPlugins());
    if (args[0] === '--check') {
      if (await readFile(output, 'utf8') !== expected) throw new Error('Plugin catalog is stale; run pnpm catalog:generate.');
      console.log('Plugin catalog is current.');
    } else { await writeFile(output, expected); console.log('Updated docs/plugins.md.'); }
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
